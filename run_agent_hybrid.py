import json
import argparse
import os
import dspy
from rich.console import Console
from rich.progress import track
from agent.graph_hybrid import RetailAgent

console = Console()

def main():
    parser = argparse.ArgumentParser(description="Run Retail Analytics Agent")
    parser.add_argument("--batch", required=True, help="Path to input JSONL file")
    parser.add_argument("--out", required=True, help="Path to output JSONL file")
    parser.add_argument("--no-opt", action="store_true", help="Disable loading of optimized modules")
    args = parser.parse_args()

    # Setup paths
    base_dir = os.path.dirname(os.path.abspath(__file__))
    db_path = os.path.join(base_dir, "data", "northwind.sqlite")
    docs_dir = os.path.join(base_dir, "docs")
    
    # Initialize Agent
    console.print(f"[bold green]Initializing Retail Agent...[/bold green]")
    agent = RetailAgent(db_path=db_path, docs_dir=docs_dir)
    graph = agent.build_graph()

    # Load optimized router if exists and not disabled
    opt_router_path = "optimized_router.json"
    if not args.no_opt and os.path.exists(opt_router_path):
        console.print(f"[bold blue]Loading optimized router from {opt_router_path}...[/bold blue]")
        try:
            agent.router.load(opt_router_path)
        except Exception as e:
            console.print(f"[bold red]Failed to load optimized router: {e}[/bold red]")
    else:
        console.print("[bold yellow]Running in BASELINE mode (no optimization loaded).[/bold yellow]")

    # Configure DSPy LM (Ensure it matches what was used in optimization/setup)
    try:
        lm = dspy.OllamaLocal(model='phi3.5:3.8b-mini-instruct-q4_K_M', max_tokens=100)
    except AttributeError:
        try:
            lm = dspy.Ollama(model='phi3.5:3.8b-mini-instruct-q4_K_M', max_tokens=100)
        except AttributeError:
            lm = dspy.LM(model='ollama/phi3.5:3.8b-mini-instruct-q4_K_M', api_base='http://localhost:11434', api_key='')
            
    dspy.settings.configure(lm=lm)

    # Read questions
    questions = []
    with open(args.batch, 'r', encoding='utf-8') as f:
        for line in f:
            if line.strip():
                questions.append(json.loads(line))

    results = []
    
    console.print(f"[bold]Processing {len(questions)} questions...[/bold]")

    for q_item in track(questions, description="Running Agent..."):
        q_id = q_item['id']
        question = q_item['question']
        format_hint = q_item['format_hint']
        
        initial_state = {
            "question": question,
            "format_hint": format_hint,
            "retries": 0,
            "error": None,
            "citations": [],
            "doc_chunks": [],
            "sql_query": "",
            "sql_result": "",
            "final_answer": None,
            "plan": {},
            "classification": ""
        }
        
        # Run graph
        # config={"recursion_limit": 10} to allow for some retries
        final_state = graph.invoke(initial_state, config={"recursion_limit": 15, "configurable": {"thread_id": q_id}})
        
        # Extract outputs
        output = {
            "id": q_id,
            "final_answer": final_state.get('final_answer'),
            "sql": final_state.get('sql_query', ""),
            "confidence": 0.8 if not final_state.get('error') else 0.4, # Simple confidence logic
            "explanation": final_state.get('explanation', "Generated by Retail Agent.") + (f" Error: {final_state.get('error')}" if final_state.get('error') else ""),
            "citations": final_state.get('citations', [])
        }
        
        # If synthesizer produced explanation, use it (we didn't explicitly capture it in state return, let's fix that if needed)
        # In graph_hybrid.py synthesizer_node returns final_answer and citations. 
        # We should probably update synthesizer_node to return explanation too if we want it in output.
        # But for now, let's stick to the contract. The contract asks for explanation.
        # Let's check graph_hybrid.py again.
        
        # Write output immediately
        with open(args.out, 'a', encoding='utf-8') as f:
            f.write(json.dumps(output) + "\n")
        
        results.append(output)

    console.print(f"[bold green]Done! Results saved to {args.out}[/bold green]")

if __name__ == "__main__":
    main()
